const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('radar', {
  getSettings: () => ipcRenderer.invoke('settings:get'),
  saveSettings: (s) => ipcRenderer.invoke('settings:set', s),
  lastScan: () => ipcRenderer.invoke('scan:last'),
  runScan: () => ipcRenderer.invoke('scan:run'),
  search: (q) => ipcRenderer.invoke('stock:search', q),
  lookup: (sym) => ipcRenderer.invoke('stock:lookup', sym),
  trackRecord: () => ipcRenderer.invoke('track:get'),
  guide: () => ipcRenderer.invoke('guide:get'),
  open: (url) => ipcRenderer.invoke('open:external', url),
  appInfo: () => ipcRenderer.invoke('app:info'),
  updateStatus: () => ipcRenderer.invoke('update:status'),
  checkUpdates: () => ipcRenderer.invoke('update:check'),
  restartToUpdate: () => ipcRenderer.invoke('update:restart'),
  openInstallerPage: () => ipcRenderer.invoke('update:installer'),
  paper: {
    get: () => ipcRenderer.invoke('paper:get'),
    watch: (syms) => ipcRenderer.invoke('paper:watch', syms),
    candles: (sym, tf) => ipcRenderer.invoke('paper:candles', sym, tf),
    order: (o) => ipcRenderer.invoke('paper:order', o),
    cancel: (id) => ipcRenderer.invoke('paper:cancel', id),
    modify: (id, changes) => ipcRenderer.invoke('paper:modify', id, changes),
    close: (sym) => ipcRenderer.invoke('paper:close', sym),
    bracket: (sym, b) => ipcRenderer.invoke('paper:bracket', sym, b),
    reset: (cash) => ipcRenderer.invoke('paper:reset', cash),
    onUpdate: (fn) => ipcRenderer.on('paper:update', (_e, d) => fn(d)),
    onTick: (fn) => ipcRenderer.on('paper:tick', (_e, d) => fn(d)),
  },
  phone: {
    info: () => ipcRenderer.invoke('phone:info'),
    set: (on) => ipcRenderer.invoke('phone:set', on),
    newToken: () => ipcRenderer.invoke('phone:newToken'),
  },
  onUpdate: (fn) => ipcRenderer.on('update:status', (_e, s) => fn(s)),
  onProgress: (fn) => ipcRenderer.on('scan:progress', (_e, p) => fn(p)),
  onResult: (fn) => ipcRenderer.on('scan:result', (_e, r) => fn(r)),
  onError: (fn) => ipcRenderer.on('scan:error', (_e, m) => fn(m)),
});
